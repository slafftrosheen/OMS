import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fixture } from "../helpers/cad-editor";
import { prepareCadImport } from "../../src/lib/components/canvas/cad-import";
import {
  DEFAULT_CAD_SETTINGS,
  cadMmPerPixel,
} from "../../src/lib/components/canvas/cad-settings";
import {
  flattenContours,
  curveBounds,
} from "../../src/lib/components/canvas/cad-curves";
const settings = { ...DEFAULT_CAD_SETTINGS, originX: 0, originY: 0 };
const read = (name: string) =>
  prepareCadImport(
    fixture().editor,
    settings,
    readFileSync(`tests/fixtures/cad-external/${name}.dxf`, "utf8"),
    { keepCoordinates: true },
  );
const near = (a: number, b: number, t = 1e-7) =>
  assert.ok(Math.abs(a - b) < t, `${a} != ${b}`);
describe("external DXF compatibility — independently generated by ezdxf", () => {
  it("imports rational hatch edges and saved dimension block geometry while reporting pattern/text limits", () => {
    const p = read("spline-hatch-dimension");
    assert.ok(p.shapes!.length > 3);
    assert.ok(
      !p.omitted.some((o) => ["HATCH", "DIMENSION", "INSERT"].includes(o.type)),
      JSON.stringify(p.omitted),
    );
    assert.ok(p.warnings.includes("import-hatch-boundary"));
    assert.ok(p.warnings.includes("import-dimension"));
    assert.ok(p.omitted.some((o) => o.type === "MTEXT" || o.type === "TEXT"));
    const b = curveBounds([p.contours[0]]),
      factor = cadMmPerPixel(settings);
    near(b.w * factor, 50);
    near(b.h * factor, 50);
  });

  it("expands a nonuniform rotated MINSERT array with correct unscaled spacing and block base", () => {
    const p = read("block-array");
    assert.deepEqual(p.omitted, []);
    assert.equal(p.shapes?.length, 12);
    const factor = cadMmPerPixel(settings),
      cs = p.contours;
    const first = cs[1].nodes[0];
    near(first.x * factor, 100);
    near(-first.y * factor, 50);
    near((cs[3].nodes[0].x - first.x) * factor, 60 * Math.cos(Math.PI / 6));
    near(-(cs[3].nodes[0].y - first.y) * factor, 60 * Math.sin(Math.PI / 6));
    assert.equal(p.shapes![0].meta?.omsVectorPaint.stroke, "#1255bb");
    // Affine ellipse: analytical extents, independently calculated.
    const b = curveBounds([cs[0]]);
    near(
      b.w * factor,
      2 * Math.hypot(10 * Math.cos(Math.PI / 6), 2.5 * Math.sin(Math.PI / 6)),
      0.002,
    );
  });
  it("imports hatch holes, circular and elliptical edge loops, filled faces, and reversed OCS", () => {
    const p = read("fills-ocs");
    assert.deepEqual(p.omitted, []);
    assert.equal(p.shapes?.length, 6);
    assert.equal((p.shapes![0].props.contours as any[]).length, 2);
    assert.equal(p.shapes![0].meta?.omsVectorPaint.fill, "#ffff00");
    assert.ok(p.warnings.includes("import-elevation"));
    const points = p.contours.at(-1)!.nodes,
      factor = cadMmPerPixel(settings);
    near(points[0].x * factor, -5);
    near(points[1].x * factor, -25);
  });
  it("imports periodic non-clamped cubic splines within 0.002 mm of independent B-spline samples", () => {
    const p = read("periodic-spline");
    assert.deepEqual(p.omitted, []);
    assert.equal(p.contours.length, 1);
    assert.equal(p.contours[0].closed, true);
    const factor = cadMmPerPixel(settings),
      points = flattenContours(p.contours, 0.0001)[0].map((q) => ({
        x: q.x * factor,
        y: -q.y * factor,
      }));
    const distance = (q: number[], a: any, b: any) => {
      const dx = b.x - a.x,
        dy = b.y - a.y,
        d = dx * dx + dy * dy,
        t = d
          ? Math.max(
              0,
              Math.min(1, ((q[0] - a.x) * dx + (q[1] - a.y) * dy) / d),
            )
          : 0;
      return Math.hypot(q[0] - a.x - t * dx, q[1] - a.y - t * dy);
    };
    for (const q of JSON.parse(
      readFileSync("tests/fixtures/cad-external/periodic-samples.json", "utf8"),
    ))
      assert.ok(
        Math.min(
          ...points.map((p, i) =>
            distance(q, p, points[(i + 1) % points.length]),
          ),
        ) <= 0.002001,
      );
  });
  it("keeps unsupported text visible in the omission report and rejects non-planar coordinates", () => {
    const text =
      "0\nSECTION\n2\nENTITIES\n0\nTEXT\n1\nNAME\n0\nLINE\n10\n0\n20\n0\n30\n1\n11\n10\n21\n0\n31\n2\n0\nENDSEC\n0\nEOF\n";
    const p = prepareCadImport(fixture().editor, settings, text, {
      unit: "mm",
      keepCoordinates: true,
    });
    assert.deepEqual(
      p.omitted.map((o) => o.type),
      ["TEXT", "LINE"],
    );
  });
});
