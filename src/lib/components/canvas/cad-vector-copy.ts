export function useVectorText() {
  const language = useSyncExternalStore(
    locale.subscribe,
    () => get(locale),
    () => "en",
  );
  const dictionary = language?.startsWith("ru")
    ? ru
    : language?.startsWith("lv")
      ? lv
      : en;
  return (key: string) => dictionary[key as Key] ?? dictionary.failed;
}
